"""Generates GorillaAkimboGuns.reds: what the scripts need to know about weapon types and guns, from weapons.json.
usage: genguns.py <out .reds>"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest

m = manifest.load()
items = manifest.item_types()   # [(item type entry, type key, type)] of the handled types


def flt(x):
    s = f'{x:.4f}'.rstrip('0')
    return s + '0' if s.endswith('.') else s


def by_type(ret, value, default, doc):
    """A function of the item type: one if per distinct value, listing its item types."""
    lines = [f'  // {d}' for d in doc]
    lines.append(f'  public static func {ret} {{')
    groups = {}
    for i, key, t in items:
        v = value(i, key, t)
        if v is not None and v != default:
            groups.setdefault(v, []).append(i['name'])
    for v, names in groups.items():
        cond = ' || '.join(f'Equals(type, gamedataItemType.{n})' for n in names)
        lines += [f'    if {cond} {{', f'      return {v};', '    }']
    lines += [f'    return {default};', '  }', '']
    return lines


def cname(s):
    return f'n"{s}"'


def boolean(b):
    return 'true' if b else 'false'


def words(names):
    names = list(dict.fromkeys(names))
    if len(names) < 2:
        return ''.join(names)
    return ', '.join(names[:-1]) + ' and ' + names[-1]


L = ['// Generated by tools/anim/gen guns from weapons.json. Do not edit.',
     'module GorillaAkimbo', '',
     'public abstract class GorillaAkimboGuns {']
L += by_type('Group(type: gamedataItemType) -> CName', lambda i, k, t: cname(t['group']), 'n"None"',
             ['Settings group of an item type; n"None" for types the mod does not handle.'])
L += by_type('NeedsArms(type: gamedataItemType) -> Bool', lambda i, k, t: boolean(t['needs_arms']), 'false',
             ['Whether guns of this item type need Gorilla Arms to be dual-wielded.'])
L += by_type('IsHandled(type: gamedataItemType) -> Bool', lambda i, k, t: 'true', 'false',
             ['Types the mod adds the game\'s DualWield tag to (every handled type).'])
L += by_type('UsesArmClips(type: gamedataItemType) -> Bool', lambda i, k, t: boolean(t['arm_clips']), 'false',
             ['Types that use the mod\'s own per-hand reload arm clips and lowered stance; the others use the game\'s',
              'dual-wield sets.'])


def fallback(i, k, t):
    if 'fallback_audio' not in i:
        return None
    a, s = i['fallback_audio'], i.get('fallback_audio_shells', i['fallback_audio'])
    return cname(a) if a == s else f'shells ? {cname(s)} : {cname(a)}'


L += by_type('FallbackAudio(type: gamedataItemType, shells: Bool) -> CName', fallback, 'n"None"',
             ['Audio set to borrow reload sounds from when a gun\'s own set has no table (shells: shell-by-shell reload).'])

L += ['  // Long partner name of a gun by its audio set, n"None" when not long.',
      '  public static func LongPartner(audio: CName) -> CName {', '    switch audio {']
for audio, name in manifest.long_audio().items():
    L += [f'      case n"{audio}":', f'        return n"{name}";']
L += ['    }', '    return n"None";', '  }', '']

kinds = [(g['topmag']['kind'], g) for _, _, _, g in manifest.topmag_guns()]
L += ['  // Top-magazine kind by audio set: 0 none; only guns whose two-handed clips ship.',
      '  public static func TopMagKind(audio: CName) -> Int32 {', '    switch audio {']
for kind, g in kinds:
    for audio in g['audio']:
        L += [f'      case n"{audio}":']
    L += [f'        return {kind};']
L += ['    }', '    return 0;', '  }', '']
DOC = {'seated': 'Clip seconds at which the magazine is seated.',
       'length': 'Clip length in seconds.',
       'down': 'Clip seconds at which both guns are out of view; the other gun\'s ammo starts going in.',
       'hold_start': 'Start of the part of the clip that is held until the other gun\'s ammo is in.',
       'hold_end': 'End of the held part.'}
for key, fn in (('seated', 'TopMagSeated'), ('length', 'TopMagLength'), ('down', 'TopMagDown'),
                ('hold_start', 'TopMagHoldStart'), ('hold_end', 'TopMagHoldEnd')):
    L += [f'  // {DOC[key]} Frames at {m["reload_clip"]["fps"]} fps, per top-magazine kind.',
          f'  public static func {fn}(kind: Int32) -> Float {{']
    for kind, g in kinds:
        L += [f'    if kind == {kind} {{', f'      return {g["topmag"]["frames"][key]}.0 / {m["reload_clip"]["fps"]}.0;', '    }']
    L += ['    return 0.0;', '  }', '']

arms = words([t['plural'] for _, _, t in items if t['needs_arms']])
L += ['  // Plural names of the types that need Gorilla Arms, for tooltips.',
      '  public static func ArmsTypeNames() -> String {', f'    return "{arms}";', '  }', '']
sec = m['reload_clip']['seconds']
L += ['  // Reload arm clip layout in clip seconds, the numbers flick.py builds with. Magazine guns: a slow tip-up until',
      '  // OpenEnd, down out of view by DropEnd, held there until HoldEnd, then the rise (RiseLength). Shell-by-shell guns',
      '  // (_02 clips): down by PlainDrop.']
for fn, key in (('OpenEnd', 'open_end'), ('DropEnd', 'drop_end'), ('HoldEnd', 'hold_end'), ('PlainDrop', 'plain_drop'),
                ('RiseLength', 'rise_length')):
    L += [f'  public static func {fn}() -> Float {{', f'    return {flt(sec[key])};', '  }', '']
# Guns with reload clips of their own (weapons.json "reload"): which gun's sets a sound set plays, and per variant
# and clip the frames the script times the reload with.
fps = m['reload_clip']['fps']
owners = {}
for g in manifest.guns():
    r = g.get('reload')
    if r:
        owners.setdefault(r.get('shares') or g['id'], []).extend(g['audio'])
byid = {g['id']: g for g in manifest.guns(True)}
L += ['  // The gun whose own reload sets a gun plays, by its audio set (guns that share a model variable share them);',
      '  // n"None" for guns on the generic reload clips.',
      '  public static func ReloadOwner(audio: CName) -> CName {', '    switch audio {']
for owner, audios in owners.items():
    for audio in audios:
        L += [f'      case n"{audio}":']
    L += [f'        return n"{owner}";']
L += ['    }', '    return n"None";', '  }', '']
RDOC = {'hide_start': ['Clip seconds from which the gun, its hand and every magazine are off screen (variant: the game\'s random',
                       'reload pick 0 to 2; empty: the empty reload clip).'],
        'hide_end': ['Clip seconds at which the hidden part ends; the fresh magazine is seated by then.'],
        'length': ['Clip length in seconds.']}
for key, fn in (('hide_start', 'ReloadHideStart'), ('hide_end', 'ReloadHideEnd'), ('length', 'ReloadLength')):
    L += [f'  // {d}' for d in RDOC[key]]
    L += [f'  public static func {fn}(owner: CName, variant: Int32, empty: Bool) -> Float {{']
    for owner in owners:
        r = byid[owner]['reload']
        take = 'A' if r['weight'] == 'light' else 'B'
        L += [f'    if Equals(owner, n"{owner}") {{']
        for v in (1, 2, 0):
            lay = r['layout'][r['slots'][v] + take]
            a, b = lay['reload'][key], lay['empty_reload'][key]
            value = f'{a}.0 / {fps}.0' if a == b else f'(empty ? {b}.0 : {a}.0) / {fps}.0'
            L += [f'      if variant == {v} {{', f'        return {value};', '      }'] if v else [f'      return {value};']
        L += ['    }']
    L += ['    return 0.0;', '  }', '']
L[-1] = '}'
open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('GorillaAkimboGuns.reds:', len(items), 'item types,', len(kinds), 'top-magazine kinds')
