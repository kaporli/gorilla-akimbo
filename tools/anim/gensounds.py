"""Generates GorillaAkimboSounds.reds: each gun's own reload sound events (from its two-handed
reload clips), keyed by the weapon record's audio name. usage: gensounds.py <arm dir> <out .reds>"""
import glob, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest

ARM, OUT = sys.argv[1], sys.argv[2]
# anim set (male) -> audio names that use it: weapons.json (arm_set, audio)
SETS = {}
for _p, _audios in manifest.sound_sets():
    SETS.setdefault(os.path.basename(_p.replace(chr(92), '/'))[:-len('.anims')], []).extend(_audios)


def fallback_lines():
    """Body of Fallback: weapons without their own set use another gun of their item type (weapons.json types)."""
    default = manifest.load()['sound_default_item_type']
    out, last = [], None

    def ret(i, pad):
        if i['fallback_audio'] == i['fallback_audio_shells']:
            return f'{pad}return n"{i["fallback_audio"]}";'
        return f'{pad}return shells ? n"{i["fallback_audio_shells"]}" : n"{i["fallback_audio"]}";'

    for i, _, _ in manifest.item_types():
        if 'fallback_audio' not in i:
            continue
        if i['name'] == default:
            last = i
            continue
        out += [f'    if Equals(type, gamedataItemType.{i["name"]}) {{', ret(i, '      '), '    }']
    return out + [ret(last, '    ')]


def events(path):
    d = json.load(open(path, encoding='utf-8'))
    out = {}
    for e in d['Data']['RootChunk']['animations']:
        name = e['Data']['animation']['Data']['name']['$value']
        evs = (e['Data'].get('events') or {}).get('Data') or {}
        lst = []
        for x in evs.get('events', []):
            x = x['Data']
            if 'Sound' in x.get('$type', ''):
                lst.append((x['startFrame'] / 30.0, x['eventName']['$value']))
        out[name] = sorted(lst)
    return out


table = {}
for stem, audios in SETS.items():
    found = glob.glob(os.path.join(ARM, '**', stem + '.anims.json'), recursive=True)
    if not found:
        raise SystemExit(f'missing {stem}.anims.json under {ARM}: run build.sh extract')
    f = found[0]
    ev = events(f)
    reload = ev.get('reload') or ev.get('empty_reload') or []
    empty = ev.get('empty_reload') or reload
    for a in audios:
        table[a] = (reload, empty)


def arr(lst, i):
    if i == 0:
        return '[' + ', '.join(f'{t:.3f}' for t, _ in lst) + ']'
    return '[' + ', '.join(f'n"{n}"' for _, n in lst) + ']'


lines = ['// Generated by gensounds.py from each weapon\'s two-handed reload clips: the sound events of its reload',
         '// (empty: of its empty reload), in clip seconds at its base reload time.',
         'module GorillaAkimbo', '',
         'public abstract class GorillaAkimboSounds {',
         '  public static func Fallback(audio: CName, type: gamedataItemType, shells: Bool) -> CName {',
         *fallback_lines(), '  }', '',
         '  public static func Has(audio: CName) -> Bool {', '    switch audio {']
for a in sorted(table):
    lines.append(f'      case n"{a}":')
lines += ['        return true;', '    }', '    return false;', '  }', '',
          '  public static func Get(audio: CName, empty: Bool, times: script_ref<array<Float>>, names: script_ref<array<CName>>) {',
          '    switch audio {']
for a in sorted(table):
    reload, emp = table[a]
    lines += [f'      case n"{a}":',
              f'        Deref(times) = empty ? {arr(emp, 0)} : {arr(reload, 0)};',
              f'        Deref(names) = empty ? {arr(emp, 1)} : {arr(reload, 1)};',
              '        break;']
lines += ['    }', '  }', '']


def mag_out(lst):
    # When the magazine (or a double-barrel's shells) leaves the gun: its first mag-out, eject or open sound.
    for key in ('mag_out', 'eject', 'open'):
        for t, n in lst:
            if key in n:
                return t
    return 0.5


lines += ['  // Clip seconds into the reload at which the magazine (or the spent shells) leaves the gun.',
          '  public static func MagOut(audio: CName, empty: Bool) -> Float {', '    switch audio {']
for a in sorted(table):
    reload, emp = table[a]
    lines += [f'      case n"{a}":', f'        return empty ? {mag_out(emp):.3f} : {mag_out(reload):.3f};']
lines += ['    }', '    return 0.5;', '  }', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(table), 'audio names ->', OUT)
