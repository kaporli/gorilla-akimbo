"""Generates GorillaAkimboSounds.reds: each SMG and shotgun's own reload sound events (from its two-handed
reload clips), keyed by the weapon record's audio name. usage: gensounds.py <arm dir> <out .reds>"""
import glob, json, os, sys

ARM, OUT = sys.argv[1], sys.argv[2]
# anim set (male) -> audio names that use it
SETS = {
    'pma_w_shotgun__budget_carnage': ['wea_set_carnage'],
    'pma_w_shotgun__constitutional_arms_tactician': ['wea_set_tactician'],
    'pma_w_shotgun_dual__rostovic_igla': ['wea_set_igla'],
    'pma_w_shotgun_dual__rostovic_palica': ['wea_set_palica'],
    'pma_w_shotgun_dual__rostovic_satara': ['wea_set_satara'],
    'pma_w_shotgun_dual__rostovic_testera': ['wea_set_testera'],
    'pma_w_special__kangtao_zhuo': ['wea_set_zhuo'],
    'pma_w_revolver__militech_crusher': ['wea_set_crusher'],
    'pma_w_rifle_precision__techtronika_pozhar': ['wea_set_pozhar'],
    'pma_w_smg__arasaka_shingen': ['wea_set_shingen'],
    'pma_w_smg__darra_pulsar': ['wea_set_pulsar'],
    'pma_w_smg__militech_saratoga': ['wea_set_saratoga'],
    'pma_w_smg__senkoh_lx': ['wea_set_senkoh', 'wea_set_senkoh_prototype'],
    'pma_w_smg__krausser_warden': ['wea_set_warden', 'wea_set_warden_suppressor'],
    'pma_w_smg__midnight_borg': ['wea_set_borg4a'],
    'pma_w_special_kangtao_dian': ['wea_set_dian'],
}
# Weapons without their own set use another gun of their type.
FALLBACK = {'smg': 'wea_set_saratoga', 'shells': 'wea_set_carnage', 'magazine': 'wea_set_crusher',
            'double': 'wea_set_igla'}


def events(path):
    d = json.load(open(path, encoding='utf-8'))
    out = {}
    for e in d['Data']['RootChunk']['animations']:
        name = e['Data']['animation']['Data']['name']['$value']
        evs = (e['Data'].get('events') or {}).get('Data') or {}
        lst = []
        for x in evs.get('events', []):
            x = x['Data']
            if 'Sound' in x.get('$type', ''):
                lst.append((x['startFrame'] / 30.0, x['eventName']['$value']))
        out[name] = sorted(lst)
    return out


table = {}
for stem, audios in SETS.items():
    f = glob.glob(os.path.join(ARM, '**', stem + '.anims.json'), recursive=True)[0]
    ev = events(f)
    reload = ev.get('reload') or ev.get('empty_reload') or []
    empty = ev.get('empty_reload') or reload
    for a in audios:
        table[a] = (reload, empty)


def arr(lst, i):
    if i == 0:
        return '[' + ', '.join(f'{t:.3f}' for t, _ in lst) + ']'
    return '[' + ', '.join(f'n"{n}"' for _, n in lst) + ']'


lines = ['// Generated by gensounds.py from each weapon\'s two-handed reload clips: the sound events of its reload',
         '// (empty: of its empty reload), in clip seconds at its base reload time.',
         'module GorillaAkimbo', '',
         'public abstract class GorillaAkimboSounds {',
         '  public static func Fallback(audio: CName, type: gamedataItemType, shells: Bool) -> CName {',
         '    if Equals(type, gamedataItemType.Wea_SubmachineGun) {',
         f'      return n"{FALLBACK["smg"]}";', '    }',
         '    if Equals(type, gamedataItemType.Wea_ShotgunDual) {',
         f'      return n"{FALLBACK["double"]}";', '    }',
         f'    return shells ? n"{FALLBACK["shells"]}" : n"{FALLBACK["magazine"]}";', '  }', '',
         '  public static func Has(audio: CName) -> Bool {', '    switch audio {']
for a in sorted(table):
    lines.append(f'      case n"{a}":')
lines += ['        return true;', '    }', '    return false;', '  }', '',
          '  public static func Get(audio: CName, empty: Bool, times: script_ref<array<Float>>, names: script_ref<array<CName>>) {',
          '    switch audio {']
for a in sorted(table):
    reload, emp = table[a]
    lines += [f'      case n"{a}":',
              f'        Deref(times) = empty ? {arr(emp, 0)} : {arr(reload, 0)};',
              f'        Deref(names) = empty ? {arr(emp, 1)} : {arr(reload, 1)};',
              '        break;']
lines += ['    }', '  }', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(table), 'audio names ->', OUT)
