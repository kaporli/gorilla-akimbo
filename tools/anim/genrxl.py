"""Writes GorillaAkimboRifles.archive.xl: the rifles' own one-handed reload arm sets and their magazine sets.

Arm sets: per rifle model variable, body and hand, [dual_wield, <model variable>] (left: <variable>_left),
priority 63: the place of the gun's per-hand reload set of today (shared or raised-pose), which genxl.py leaves out
for these variables in a test build; one below the shared set of the base variable (64), which the gun also carries. A rifle without an entry here (modded rifles) keeps the shared set.

Magazine sets: the weapon entity template (weapon_root.ent, shared by every player weapon) cannot be keyed on the
player's model variable, so each set is keyed on a wrapper the script turns on on that gun while it reloads
dual-wielded: gorillaakimbo_rmag_<gun>_<body>_<side>. The rifles' appearances play the magazine set on two animated
components, Magazine and MagazineReload (the second magazine mesh), so each set gets an entry for both. Copperhead,
Umbra and Sidewinder share one vanilla magazine set file; that does not matter here, the wrapper decides.

usage: genrxl.py <out .archive.xl> [built sets dir]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest, rreload

PACKED = sys.argv[2] if len(sys.argv) > 2 else None
built = lambda n: PACKED is None or os.path.exists(os.path.join(PACKED, n + '.anims'))
ENT = {b: manifest.entities(b) for b in manifest.bodies()}
MAG_ENTITY = manifest.depot(manifest.load()['game_files']['magazine_entity'])
lines = ['# Gorilla Akimbo: one-handed rifle reloads per gun (arm clips and magazine tracks).', '# Generated by genrxl.py.', 'animations:']
wr = []
for g, body, side, aname, mname, _ in rreload.plan():
    if built(aname):
        for var in manifest.gun_vars(g):
            lines += ['  - entity: [' + ', '.join(ENT[body]) + ']', f'    set: gorillaakimbo\\animations\\{aname}.anims',
                      '    vars: [dual_wield, ' + var + ('' if side == 'right' else '_left') + ']', '    priority: 63']
    if built(mname):
        w = rreload.wrapper(body, side, g['id']); wr.append(w)
        for comp in g['reload']['magazine'].get('components', ['Magazine', 'MagazineReload']):
            lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{mname}.anims', f'    vars: [{w}]', '    priority: 100']
open(sys.argv[1], 'w', newline='\n').write('\n'.join(lines) + '\n')
print(sum(1 for l in lines if l.startswith('  - ')), 'entries,', len(wr), 'wrappers')
