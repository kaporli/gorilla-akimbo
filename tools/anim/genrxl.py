"""Writes GorillaAkimboRifles.archive.xl: the rifles' own one-handed reload arm sets and their magazine sets.

Arm sets: per rifle model variable, body and hand, [dual_wield, <model variable>] (left: <variable>_left),
priority 63: the place of the gun's per-hand reload set of today (shared or raised-pose), which genxl.py leaves out
for these variables in a test build; one below the shared set of the base variable (64), which the gun also carries. A rifle without an entry here (modded rifles) keeps the shared set.

Magazine sets: the weapon entity template (weapon_root.ent, shared by every player weapon) cannot be keyed on the
player's model variable, so each set is keyed on a wrapper the script turns on on that gun while it reloads
dual-wielded: gorillaakimbo_rmag_<gun>_<body>_<side>. The rifles' appearances play the magazine set on two animated
components, Magazine and MagazineReload (the second magazine mesh), so each set gets an entry for both. Copperhead,
Umbra and Sidewinder share one vanilla magazine set file; that does not matter here, the wrapper decides.

SMGs and shotguns (GorillaAkimboSmgShotgun.archive.xl) the same way; a gun without a magazine set (shell-by-shell tube
guns) has arm set entries only. The archive is the output file's name; only guns whose reload.archive is that one.

usage: genrxl.py <out .archive.xl> [built sets dir]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest, rreload

PACKED = sys.argv[2] if len(sys.argv) > 2 else None
built = lambda n: PACKED is None or os.path.exists(os.path.join(PACKED, n + '.anims'))
ENT = {b: manifest.entities(b) for b in manifest.bodies()}
MAG_ENTITY = manifest.depot(manifest.load()['game_files']['magazine_entity'])
ARCHIVE = os.path.basename(sys.argv[1])[:-len('.archive.xl')]
WHAT = 'rifle' if ARCHIVE == rreload.ARCHIVE else 'SMG and shotgun'
lines = [f'# Gorilla Akimbo: one-handed {WHAT} reloads per gun (arm clips and magazine tracks).', '# Generated by genrxl.py.', 'animations:']
wr = []
for g, body, side, aname, mname, _ in rreload.plan():
    if rreload.archive(g) != ARCHIVE:
        continue
    if built(aname):
        for var in manifest.gun_vars(g):
            lines += ['  - entity: [' + ', '.join(ENT[body]) + ']', f'    set: gorillaakimbo\\animations\\{aname}.anims',
                      '    vars: [dual_wield, ' + var + ('' if side == 'right' else '_left') + ']', '    priority: 63']
    if mname and built(mname):
        w = rreload.wrapper(body, side, g['id']); wr.append(w)
        for comp in g['reload']['magazine'].get('components', ['Magazine', 'MagazineReload']):
            lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{mname}.anims', f'    vars: [{w}]', '    priority: 100']
# Lowered-stance variants (reload.lowered_variant, rreload.low_plan): the arm set of the variant clips with the gun's variable and the player wrapper
# (set by the script when the reload starts in the lowered stance), at priority 62, a lower number than the gun's own set (63): the lower number wins; the magazine set of the variant clips on its own
# wrapper (gorillaakimbo_rmagl_<gun>_<body>_<side>), which the script turns on instead of the shipped set's.
for g, body, side, aname, mname, _ in rreload.low_plan():
    if rreload.archive(g) != ARCHIVE:
        continue
    lv = rreload.lowered(g)
    if built(aname):
        for var in manifest.gun_vars(g):
            lines += ['  - entity: [' + ', '.join(ENT[body]) + ']', f'    set: gorillaakimbo\\animations\\{aname}.anims',
                      '    vars: [dual_wield, ' + var + ('' if side == 'right' else '_left') + ', ' + lv['wrapper'] + ']', f"    priority: {lv['priority']}"]
    if mname and built(mname):
        w = rreload.low_mag_wrapper(body, side, g['id']); wr.append(w)
        for comp in g['reload']['magazine'].get('components', ['Magazine', 'MagazineReload']):
            lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{mname}.anims', f'    vars: [{w}]', '    priority: 100']
# Gun part sets (reload.parts: shell-fed guns, rpartset.py): the barrel set on the gun's Barrel component and the shell
# set on its two shell components, keyed on the same wrapper the script turns on for a magazine set
# (gorillaakimbo_rmag_<gun>_<body>_<side>, the fallback's gorillaakimbo_rmagq_<gun>).
for g, body, side, bname, sname, _ in rreload.parts_plan():
    if rreload.archive(g) != ARCHIVE:
        continue
    w = rreload.wrapper(body, side, g['id']); pr = g['reload']['parts']
    for n, comps in ((bname if rreload.ships_barrels(g) else None, pr.get('barrel_components', ['Barrel'])), (sname, pr.get('shell_components', ['Magazine', 'MagazineReload']))):
        if not n or not built(n): continue
        wr.append(w)
        for comp in comps:
            lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{n}.anims', f'    vars: [{w}]', '    priority: 100']
# Handle part sets (rule H1, hpartset.py): the weapon set's cocking handle (bolt, slider, lever) played inside the clip's hidden window, on the Barrel component (the component of the gun's base1 set,
# as the tube guns' barrel sets; unverified for these guns in game), keyed on the same wrapper as the magazine set of the same arm set.
for g, body, side, hname, low, _ in rreload.handle_plan():
    if rreload.archive(g) != ARCHIVE or not built(hname):
        continue
    w = rreload.low_mag_wrapper(body, side, g['id']) if low else rreload.wrapper(body, side, g['id']); wr.append(w)
    for comp in g['reload'].get('handle_components', ['Barrel']):
        lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{hname}.anims', f'    vars: [{w}]', '    priority: 100']
for g, bname, sname, _ in rreload.quick_parts_plan():
    if rreload.archive(g) != ARCHIVE:
        continue
    w = rreload.quick_wrapper(g['id']); pr = g['reload']['parts']
    for n, comps in ((bname if rreload.ships_barrels(g) else None, pr.get('barrel_components', ['Barrel'])), (sname, pr.get('shell_components', ['Magazine', 'MagazineReload']))):
        if not n or not built(n): continue
        wr.append(w)
        for comp in comps:
            lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{n}.anims', f'    vars: [{w}]', '    priority: 100']
wr = list(dict.fromkeys(wr))
# Quick-drop fallback (guns with reload.fallback and a magazine): one magazine set per gun, every slot seated with the
# swap out of view, keyed on gorillaakimbo_rmagq_<gun>, which the script turns on instead of the picks' wrapper.
for g, q in rreload.quick_plan():
    if rreload.archive(g) != ARCHIVE or not built(q):
        continue
    w = rreload.quick_wrapper(g['id']); wr.append(w)
    for comp in g['reload']['magazine'].get('components', ['Magazine', 'MagazineReload']):
        lines += [f'  - entity: {MAG_ENTITY}', f'    component: {comp}', f'    set: gorillaakimbo\\animations\\{q}.anims', f'    vars: [{w}]', '    priority: 100']
open(sys.argv[1], 'w', newline='\n').write('\n'.join(lines) + '\n')
print(sum(1 for l in lines if l.startswith('  - ')), 'entries,', len(wr), 'wrappers')
