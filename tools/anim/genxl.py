"""Writes GorillaAkimbo.archive.xl: dual-wield arm animations for SMGs and shotguns.

The player entity picks arm animation sets by animation variables. Pistols and revolvers have sets for
'dual_wield' + their model variable (and '<model>_left'); SMGs and shotguns have none. These entries give
every SMG and shotgun model variable (and the base ones modded weapons fall back to) the Gorilla Akimbo
arm sets, per hand, for male (pma) and female (pwa) V.
"""
import sys

# Model variables of the player's SMG and shotgun arm sets (player_ma_fpp / player_wa_fpp and the ep1 ones).
MODELS = [
    'w_submachinegun_arasaka_shingen', 'w_submachinegun_arasaka_senkoh', 'w_submachinegun_darra_pulsar',
    'w_submachinegun_militech_saratoga', 'w_submachinegun_krausser_warden', 'warden_iconic',
    'w_smg_midnight_borg', 'w_special_kangtao_dian', 'w_smart_corp_rifle_21301_a', 'w_base_submachinegun',
    'w_shotgun_budget_carnage', 'w_shotgun_constitutional_tactician', 'w_shotgun_zhuo',
    'w_revolver_militech_crusher', 'w_rifle_precision__techtronika_pozhar',
    'w_shotgun_dual_rostovic_igla', 'w_shotgun_dual_rostovic_palica', 'w_shotgun_dual_rostovic_testera',
    'w_2020_shotgun_blunderbuss', 'w_base_shotgun', 'w_base_shotgun_dual',
]
ENTITIES = {
    'pma': ['base\\characters\\entities\\player\\player_ma_fpp.ent', 'ep1\\characters\\entities\\player\\player_ma_fpp_ep1.ent'],
    'pwa': ['base\\characters\\entities\\player\\player_wa_fpp.ent', 'ep1\\characters\\entities\\player\\player_wa_fpp_ep1.ent'],
}

lines = ['# Gorilla Akimbo: arm animations for dual-wielded SMGs and shotguns, per hand.',
         '# Generated by genxl.py.', 'animations:']
for body, entities in ENTITIES.items():
    for model in MODELS:
        for side, suffix in (('right', ''), ('left', '_left')):
            lines.append('  - entity: [' + ', '.join(entities) + ']')
            lines.append(f'    set: gorillaakimbo\\animations\\{body}_dual_wield_{side}_lowered.anims')
            lines.append('    vars: [dual_wield, ' + model + suffix + ']')
            lines.append('    priority: 64')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(lines) + '\n')
print(sum(1 for l in lines if l.startswith('  - ')), 'entries')
