"""Writes GorillaAkimbo.archive.xl: dual-wield arm animations for the guns of weapons.json that use the mod's arm clips.

The player entity picks arm animation sets by animation variables. Pistols and revolvers have sets for
'dual_wield' + their model variable (and '<model>_left'); SMGs and shotguns have none. These entries give
every such model variable (and the base ones modded weapons fall back to) the Gorilla Akimbo
arm sets, per hand, for male (pma) and female (pwa) V.

usage: genxl.py <out .archive.xl> [packed animations dir]
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest
import raisedsets
from topmagsets import plan

# Optional second argument: the packed animations folder; top-magazine sets missing from it are left out.
PACKED = sys.argv[2] if len(sys.argv) > 2 else None


def built(name):
    return PACKED is None or os.path.exists(os.path.join(PACKED, name + '.anims'))


# Model variables of the player's arm sets (player_ma_fpp / player_wa_fpp and the ep1 ones): weapons.json.
MODELS = manifest.models()
ENTITIES = {body: manifest.entities(body) for body in manifest.bodies()}
# Guns with a raised pose of their own (raisedsets.py): their own per-hand reload set instead of the shared one, and
# the raised pose set.
RAISED = raisedsets.poses()

lines = ['# Gorilla Akimbo: arm animations for dual-wielded SMGs and shotguns, per hand.',
         '# Generated by genxl.py.', 'animations:']
# Rifles with their own one-handed reload sets (rreload.py, test content): genrxl.py enters those in this place.
# A gun's own model variable gets 63, a base variable 64: a gun carries both, and its own reload set (raised pose,
# rifle reloads) must win over the shared one of its base variable (a tie played the shared clips, seen in game).
BASE = set(manifest.base_vars())
import rreload
RRELOAD = rreload.variables()
for body, entities in ENTITIES.items():
    for model in MODELS:
        if model in RRELOAD:
            continue
        for side, suffix in (('right', ''), ('left', '_left')):
            lines.append('  - entity: [' + ', '.join(entities) + ']')
            name = manifest.raised_reload_set(body, side, RAISED[model]) if model in RAISED else manifest.reload_set(body, side)
            lines.append(f'    set: gorillaakimbo\\animations\\{name}.anims')
            lines.append('    vars: [dual_wield, ' + model + suffix + ']')
            lines.append('    priority: ' + ('64' if model in BASE else '63'))
# The raised pose sets: the pose clips of the game's dual-wield base set, per hand, for the guns that have one.
for body, side, kind, name, _, _, entries in raisedsets.plan():
    if kind != 'base':
        continue
    for vars_, priority in entries:
        lines.append('  - entity: [' + ', '.join(ENTITIES[body]) + ']')
        lines.append(f'    set: gorillaakimbo\\animations\\{name}.anims')
        lines.append('    vars: [' + ', '.join(vars_) + ']')
        lines.append(f'    priority: {priority}')
# Guns of a handled type that uses the game's dual-wield sets but has none of its own: another gun's sets, at the
# priority the game gives a gun's own sets.
for model, template in manifest.borrowed_sets():
    for body, entities in ENTITIES.items():
        for side, suffix in (('right', ''), ('left', '_left')):
            lines.append('  - entity: [' + ', '.join(entities) + ']')
            lines.append('    set: ' + manifest.depot(template.format(body=body, side=side)))
            lines.append('    vars: [dual_wield, ' + model + suffix + ']')
            lines.append('    priority: 64')
# Top-magazine guns (topmagsets.py): two-handed reload clips, over the per-hand sets (a lower number wins: the
# game's own per-model dual-wield sets use 64, its base dual-wield set 100, the two-handed SMG sets 128). Strict tiers
# (topmagsets.PRIO): long partner 57 (base variable 58), two top-magazine guns 59, size category partner 60 (base
# variable 61), default 63.
CLIPS = manifest.path('clips')
for body, name, _, entries in plan(CLIPS):
    if not built(name):
        continue
    for vars_, priority in entries:
        lines.append('  - entity: [' + ', '.join(ENTITIES[body]) + ']')
        lines.append(f'    set: gorillaakimbo\\animations\\{name}.anims')
        lines.append('    vars: [dual_wield, ' + ', '.join(vars_) + ']')
        lines.append(f'    priority: {priority}')
# The top-magazine gun's magazine while dual-wielding (magtrack.py): the magazine stays seated until the other gun hits
# it, then flies off. The Shingen's appearance (w_smg__arasaka_shingen.app) embeds the magazine as the animated
# component "Magazine" of the weapon entity, so the entry targets the weapon entity template (weapon_root.ent, shared
# by all player weapons) with component: Magazine. The sets only play while the script sets their wrapper on the gun
# (GorillaAkimboTopMag.SetFamily); the vanilla magazine set has priority 128.
MAG_ENTITY = manifest.depot(manifest.load()['game_files']['magazine_entity'])
mag = manifest.magazine()
for family in (mag['families'] if mag else ()):
    for side in ('left', 'right'):
        name = f'{mag["set_prefix"]}_{family}_{side}'
        if not built(name):
            continue
        lines.append(f'  - entity: {MAG_ENTITY}')
        lines.append('    component: Magazine')
        lines.append(f'    set: gorillaakimbo\\animations\\{name}.anims')
        lines.append(f'    vars: [gorillaakimbo_mag_{family}_{side}]')
        lines.append('    priority: 100')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(lines) + '\n')
print(sum(1 for l in lines if l.startswith('  - ')), 'entries')
